const normalizeForMatch = (s: string) => s.normalize('NFKC').toLowerCase()

/**
 * 商品名（とメーカー名）からカテゴリを提案する。確定はしない。
 * 一致しなければ undefined を返し、画面側は何も提案しない（「その他」を押し付けない）。
 */
export const suggestCategory = (name: string, brand?: string): string | undefined => {
  const hay = normalizeForMatch(`${name} ${brand ?? ''}`)
  if (!hay.trim()) return undefined
  for (const [major, minor, keywords] of RULES) {
    if (keywords.some((k) => hay.includes(normalizeForMatch(k)))) return categoryId(major, minor)
  }
  return undefined
}
