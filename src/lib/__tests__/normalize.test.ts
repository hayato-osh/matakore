// 商品名とメーカーの分離。EC の brand 欄はシリーズ名なので、タイトル中のメーカー名を優先する
test.each([
  [
    '青の洞窟 ピッコリーノ スモークチーズのカルボナーラ120g・1人前 1セット（2個）日清製粉ウェルナ パスタソース レンジ対応',
    '青の洞窟',
    { name: '青の洞窟 ピッコリーノ スモークチーズのカルボナーラ', brand: '日清製粉ウェルナ' },
  ],
  [
    "青の洞窟 CLASSIC クラシックボロネーゼ'95 1セット（1箱（140g）×3）　パスタソース　レンジ対応　日清製粉ウェルナ",
    '青の洞窟',
    { name: "青の洞窟 CLASSIC クラシックボロネーゼ'95", brand: '日清製粉ウェルナ' },
  ],
  ['(10個セット) パスタソース 青の洞窟 ペペロンチーニ 1人前×2袋 46g 日清製粉ウェルナ Welna *', '日清製粉ウェルナ', { name: '青の洞窟 ペペロンチーニ', brand: '日清製粉ウェルナ' }],
  ['無印良品 素材を生かしたカレー バターチキン 180g（1人前） 1セット（1袋×2） 良品計画（イチオシ）', '無印良品', { name: '素材を生かしたカレー バターチキン', brand: '無印良品' }],
  ['【送料無料】ハウス こくまろカレー 中辛 140g×5個 まとめ買い', undefined, { name: 'こくまろカレー 中辛', brand: 'ハウス食品' }],
  ['サッポロ一番 みそラーメン 5食パック', undefined, { name: 'みそラーメン', brand: 'サンヨー食品' }],
  ['創味　ハコネーゼ　ゴーダチーズと香味野菜の濃厚ボロネーゼ　１００ｇ　１食', 'ハコネーゼ', { name: 'ハコネーゼ ゴーダチーズと香味野菜の濃厚ボロネーゼ', brand: '創味食品' }],
  ['ヤマモリ　タイカレー　プーパッポン　保存料不使用　160g・1人前　1セット（3個）', 'ヤマモリ', { name: 'タイカレー プーパッポン 保存料不使用', brand: 'ヤマモリ' }],
  // 辞書に無いメーカーは brand 欄の値をそのまま使う
  ['謎の商店 ふしぎな飴 100g', 'ナゾ製菓', { name: '謎の商店 ふしぎな飴', brand: 'ナゾ製菓' }],
  // 「日清食品」と「日清製粉ウェルナ」を混同しない
  ['日清食品 カップヌードル シーフード', undefined, { name: 'カップヌードル シーフード', brand: '日清食品' }],
])('%s → %o', (raw, hint, expected) => {
  expect(splitProduct(raw, hint)).toEqual(expected)
})

test('メーカー名を外して名前が消えるなら外さない', () => {
  expect(splitProduct('カルビー', undefined)).toEqual({ name: 'カルビー', brand: 'カルビー' })
})
