const norm = (s: string) => s.normalize('NFKC').toLowerCase()

/** 別名 → 正規名。長い別名から先に照合する */
const ALIASES: { alias: string; canonical: string }[] = MAKERS.flatMap(([canonical, ...aliases]) =>
  [canonical, ...aliases].map((alias) => ({ alias: norm(alias), canonical })),
).sort((a, b) => b.alias.length - a.alias.length)

/** 文字列の中にメーカー名があれば正規名を返す */
export const findMaker = (text: string | undefined): string | undefined => {
  if (!text) return undefined
  const hay = norm(text)
  return ALIASES.find(({ alias }) => hay.includes(alias))?.canonical
}

/** 空白区切りのトークンのうち、そのメーカーの名前そのものであるものを外す */
export const stripMakerTokens = (name: string, canonical: string) => {
  const names = new Set(ALIASES.filter((a) => a.canonical === canonical).map((a) => a.alias))
  return name
    .split(' ')
    .filter((t) => !names.has(norm(t)))
    .join(' ')
}
